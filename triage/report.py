"""Run the full evaluation and write the results to reports/."""
from pathlib import Path

import pandas as pd

from . import config
from .data import load_clean
from .evaluate import (
    compare_models,
    coverage_table,
    nested_cv,
    out_of_fold_proba,
    per_ticket_results,
    summary_metrics,
)
from .lexicon import PATTERNS, pattern_usage
from .models import CANDIDATES, FINAL_MODEL, logreg_word_char_keywords
from .policy import DEFAULT_TARGET_ACCURACY, choose_threshold


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    def fmt(v):
        return floatfmt.format(v) if isinstance(v, float) else str(v)

    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, sep, *body])


def _comparison_md(table: pd.DataFrame) -> str:
    t = pd.DataFrame({
        "model": table["model"],
        "accuracy": [f"{m:.3f} ± {s:.3f}" for m, s in zip(table["accuracy_mean"], table["accuracy_std"])],
        "macro F1": [f"{m:.3f} ± {s:.3f}" for m, s in zip(table["macro_f1_mean"], table["macro_f1_std"])],
        "log loss": table["log_loss_mean"].round(3),
    })
    return md_table(t)


def _per_class_md(per_class: dict) -> str:
    rows = [
        {"category": c, "precision": per_class[c]["precision"], "recall": per_class[c]["recall"],
         "f1": per_class[c]["f1-score"], "support": int(per_class[c]["support"])}
        for c in config.CATEGORIES
    ]
    return md_table(pd.DataFrame(rows))


def _keyword_robustness(df: pd.DataFrame) -> tuple[pd.DataFrame, str]:
    """Drop every keyword pattern that matches exactly one labelled ticket and re-score.

    Patterns hitting a single ticket are the ones most likely written *for*
    that ticket, so this approximates the score without that leakage.
    """
    usage = pd.DataFrame(pattern_usage(df["text"]), columns=["category", "pattern", "labelled_tickets_matched"])
    single = set(usage.loc[usage["labelled_tickets_matched"] == 1, "pattern"])
    reduced = {cat: [p for p in pats if p not in single] for cat, pats in PATTERNS.items()}
    variants = {
        "all keyword patterns": logreg_word_char_keywords,
        f"without the {len(single)} single-ticket patterns": lambda: logreg_word_char_keywords(reduced),
        "no keyword patterns": CANDIDATES["logreg_word_char_tfidf"],
    }
    table = compare_models(df["text"], df["label"], variants)
    counts = usage["labelled_tickets_matched"]
    summary = (
        f"{len(usage)} patterns: {(counts == 0).sum()} match no labelled ticket, "
        f"{(counts == 1).sum()} match exactly one, {(counts >= 2).sum()} match two or more."
    )
    return usage, summary + "\n\n" + _comparison_md(table)


def run(out_dir: Path = config.REPORTS_DIR) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    df = load_clean()

    print("Comparing models on corrected labels...")
    comp_clean = compare_models(df["text"], df["label"], CANDIDATES)
    print("Comparing models on original labels...")
    comp_orig = compare_models(df["text"], df["original_label"], CANDIDATES)
    comp_clean.to_csv(out_dir / "model_comparison_corrected_labels.csv", index=False)
    comp_orig.to_csv(out_dir / "model_comparison_original_labels.csv", index=False)

    print("Nested CV (selection-bias check)...")
    nested = nested_cv(df["text"], df["label"], CANDIDATES)

    print(f"Leave-one-out predictions for {FINAL_MODEL}...")
    final = CANDIDATES[FINAL_MODEL]
    proba = out_of_fold_proba(final(), df["text"], df["label"])
    results = per_ticket_results(df, proba)
    metrics = summary_metrics(results["true_label"], results["predicted"])

    proba_orig = out_of_fold_proba(final(), df["text"], df["original_label"])
    pred_orig = proba_orig.idxmax(axis=1)
    metrics_orig = summary_metrics(df["original_label"], pred_orig)

    coverage = coverage_table(proba, df["label"])
    threshold = choose_threshold(coverage)

    print("Keyword robustness check...")
    usage, robustness_md = _keyword_robustness(df)

    results.to_csv(out_dir / "oof_predictions.csv", index=False)
    results[~results["correct"]].to_csv(out_dir / "errors.csv", index=False)
    coverage.to_csv(out_dir / "coverage_curve.csv", index=False)
    metrics["confusion"].to_csv(out_dir / "confusion_matrix.csv")
    usage.to_csv(out_dir / "keyword_pattern_usage.csv", index=False)

    errors = results[~results["correct"]][
        ["ticket_id", "text", "true_label", "predicted", "confidence", "second_choice", "ambiguous"]
    ]
    at_threshold = coverage[coverage["threshold"] == threshold].iloc[0]
    lo, hi = metrics["accuracy_ci95"]
    lo_o, hi_o = metrics_orig["accuracy_ci95"]

    md = f"""# Evaluation report

Generated by `python -m triage evaluate`. All scores are out-of-fold: a ticket is
only scored by a model that never saw it in training. 40 labelled tickets, so
expect wide error bars.

## 1. Model comparison (corrected labels)

Repeated stratified 5-fold cross-validation, 10 repeats (50 fits per model), mean ± std across folds.

{_comparison_md(comp_clean)}

## 2. Model comparison (original, uncorrected labels)

Same set-up, trained and scored on the labels exactly as supplied.

{_comparison_md(comp_orig)}

## 3. Selection-bias check (nested CV)

The inner loop picks the best candidate by macro F1; the outer loop (5-fold × 3) scores that choice
on data the selection never saw.

- Accuracy of the "pick the best model" procedure: **{nested['accuracy_mean']:.3f} ± {nested['accuracy_std']:.3f}**
- Models chosen by the inner loop: {nested['chosen']}

## 4. Final model: `{FINAL_MODEL}` (leave-one-out)

| labels | accuracy | 95% CI (Wilson) | macro F1 |
|---|---|---|---|
| corrected | {metrics['accuracy']:.3f} ({metrics['correct']}/{metrics['n']}) | {lo:.2f} – {hi:.2f} | {metrics['macro_f1']:.3f} |
| original | {metrics_orig['accuracy']:.3f} ({metrics_orig['correct']}/{metrics_orig['n']}) | {lo_o:.2f} – {hi_o:.2f} | {metrics_orig['macro_f1']:.3f} |

### Per category (corrected labels)

{_per_class_md(metrics['per_class'])}

### Confusion matrix (corrected labels; rows = true, columns = predicted)

{md_table(metrics['confusion'].reset_index().rename(columns={'index': ''}))}

### Where it goes wrong

{md_table(errors) if len(errors) else 'No errors.'}

## 5. Confidence threshold and needs-human rate

Accuracy on the tickets that would be routed automatically at each confidence threshold.

{md_table(coverage)}

Chosen threshold: **{threshold:.2f}** (lowest threshold with at least {DEFAULT_TARGET_ACCURACY:.0%} auto-routed
accuracy, never below 0.5). At this threshold {int(at_threshold['auto_routed'])}/{len(df)}
({at_threshold['coverage']:.0%}) tickets are auto-routed with {at_threshold['auto_accuracy']:.0%} accuracy;
the rest go to a person. Safety overrides (card data, security, outage, legal) add to that.

## 6. How much of the score comes from the keyword list?

The keyword patterns were written after reading the labelled tickets, so they partly leak into
the evaluation. Patterns that match exactly one labelled ticket are the most likely to be
tailored to it. Removing them and re-scoring gives a less flattering estimate.

{robustness_md}

Full list: `reports/keyword_pattern_usage.csv`.
"""
    (out_dir / "metrics.md").write_text(md, encoding="utf-8")
    print(f"Wrote {out_dir / 'metrics.md'}")
    return {"metrics": metrics, "threshold": threshold, "nested": nested}
